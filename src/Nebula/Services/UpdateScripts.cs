using System;
using System.Collections.Generic;
using System.IO;

namespace Nebula.Services;

/// <summary>
/// Generates the two PowerShell halves of the update transaction. The apply
/// script waits for a health receipt from the new build; the recovery script is
/// the RunOnce fallback for a power loss or a killed updater.
/// </summary>
internal static class UpdateScripts
{
    private const string RunOnceKey = @"HKCU:\Software\Microsoft\Windows\CurrentVersion\RunOnce";
    private const string RunOnceName = "NebulaUpdateRecovery";

    private static string Q(string value) => "'" + value.Replace("'", "''") + "'";

    public static string Apply(string appDirectory, string staging, string token, string targetVersion,
        string targetSha)
    {
        string root = Path.GetDirectoryName(staging)!;
        string updated = appDirectory + ".new";
        string previous = appDirectory + ".old";
        string failed = appDirectory + ".failed";
        string state = Path.Combine(root, "update-state.json");
        string confirmation = Path.Combine(root, "update-confirmed.txt");
        string failure = Path.Combine(root, "update-failed.txt");
        string failedVersion = Path.Combine(root, "failed-update.json");
        string log = Path.Combine(root, "apply-update.log");
        string zip = Path.Combine(root, "update.zip");
        int pid = Environment.ProcessId;

        return string.Join(Environment.NewLine, new List<string>
        {
            "$ErrorActionPreference = 'Stop'",
            "Set-Location -LiteralPath $env:SystemRoot",
            "$log = " + Q(log),
            "$failureReport = " + Q(failure),
            "$pidToWait = " + pid,
            "$source = " + Q(staging),
            "$destination = " + Q(appDirectory),
            "$updated = " + Q(updated),
            "$previous = " + Q(previous),
            "$failed = " + Q(failed),
            "$zip = " + Q(zip),
            "$state = " + Q(state),
            "$confirmation = " + Q(confirmation),
            "$failedVersionFile = " + Q(failedVersion),
            "$targetVersion = " + Q(targetVersion),
            "$targetSha = " + Q(targetSha),
            "$token = " + Q(token),
            "$runOnceKey = " + Q(RunOnceKey),
            "$runOnceName = " + Q(RunOnceName),
            "",
            "function Write-Log([string]$message) {",
            "  $line = '[{0}] {1}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $message",
            "  Add-Content -LiteralPath $log -Value $line -Encoding utf8",
            "}",
            "",
            "function Get-Confirmed {",
            "  if (!(Test-Path -LiteralPath $confirmation)) { return $false }",
            "  try {",
            "    $line = Get-Content -LiteralPath $confirmation -TotalCount 1 -ErrorAction Stop",
            "    return $line.Trim() -eq $token",
            "  } catch { return $false }",
            "}",
            "",
            "function Clear-RunOnce {",
            "  Remove-ItemProperty -Path $runOnceKey -Name $runOnceName -ErrorAction SilentlyContinue",
            "}",
            "",
            "function Stop-UpdateProcesses {",
            "  if ($null -ne $newProcess -and -not $newProcess.HasExited) {",
            "    try { $newProcess.CloseMainWindow() | Out-Null } catch { }",
            "    Start-Sleep -Milliseconds 600",
            "    try { if (-not $newProcess.HasExited) { $newProcess.Kill() } } catch { }",
            "  }",
            "  # Kill the app before the watchdog: the watchdog needs to see the",
            "  # parent disappear so it can show the native bar again. Killing it",
            "  # first used to leave the user without any taskbar after a rollback.",
            "  Get-Process -Name 'Nebula' -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue",
            "  Start-Sleep -Milliseconds 1500",
            "  Get-Process -Name 'Nebula.Watchdog' -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue",
            "}",
            "",
            "function Write-Failure([string]$message) {",
            "  $report = @('Aggiornamento non riuscito il ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $message) -join [Environment]::NewLine",
            "  Set-Content -LiteralPath $failureReport -Value $report -Encoding utf8",
            "}",
            "function Write-FailedPackage {",
            "  [ordered]@{ Version = $targetVersion; Sha256 = $targetSha; FailedUtc = (Get-Date).ToUniversalTime().ToString('O') } | ConvertTo-Json | Set-Content -LiteralPath $failedVersionFile -Encoding utf8",
            "}",
            "",
            "Write-Log ('Waiting for Nebula (PID ' + $pidToWait + ') to exit.')",
            "while (Get-Process -Id $pidToWait -ErrorAction SilentlyContinue) { Start-Sleep -Milliseconds 200 }",
            "$watchdogDeadline = (Get-Date).AddSeconds(8)",
            "while ((Get-Process -Name 'Nebula.Watchdog' -ErrorAction SilentlyContinue) -and ((Get-Date) -lt $watchdogDeadline)) { Start-Sleep -Milliseconds 200 }",
            "",
            "$newProcess = $null",
            "$confirmed = $false",
            "$failure = ''",
            "try {",
            "  if (Test-Path -LiteralPath $previous) { throw 'Esiste già una cartella .old da un aggiornamento precedente.' }",
            "  if (Test-Path -LiteralPath $updated) { Remove-Item -LiteralPath $updated -Recurse -Force }",
            "  New-Item -ItemType Directory -Path $updated -Force | Out-Null",
            "  Copy-Item -Path (Join-Path $source '*') -Destination $updated -Recurse -Force",
            "  if (!(Test-Path -LiteralPath (Join-Path $updated 'Nebula.exe'))) { throw 'Il pacchetto non contiene Nebula.exe.' }",
            "  Get-ChildItem -LiteralPath $destination -Filter 'unins*' -File -Force | ForEach-Object { Copy-Item -LiteralPath $_.FullName -Destination $updated -Force }",
            "  $moved = $false",
            "  for ($attempt = 1; $attempt -le 20; $attempt++) {",
            "    try { [System.IO.Directory]::Move($destination, $previous); $moved = $true; break }",
            "    catch { Start-Sleep -Milliseconds 250 }",
            "  }",
            "  if (!$moved) { throw 'La cartella di Nebula è ancora in uso.' }",
            "  try {",
            "    [System.IO.Directory]::Move($updated, $destination)",
            "    Write-Log 'Aggiornamento applicato; attendo la conferma della nuova build.'",
            "  } catch {",
            "    [System.IO.Directory]::Move($previous, $destination)",
            "    throw",
            "  }",
            "",
            "  Remove-Item -LiteralPath $confirmation -Force -ErrorAction SilentlyContinue",
            "  $launch = Join-Path $destination 'Nebula.exe'",
            "  for ($attempt = 1; $attempt -le 3 -and $null -eq $newProcess; $attempt++) {",
            "    $newProcess = Start-Process -FilePath $launch -ArgumentList '--startup' -PassThru -ErrorAction SilentlyContinue",
            "    if ($null -eq $newProcess) { Start-Sleep -Milliseconds 600 }",
            "  }",
            "  if ($null -eq $newProcess) { throw 'La nuova build non è stata avviata.' }",
            "  Write-Log ('Nuova build avviata (PID ' + $newProcess.Id + '); attendo la conferma di avvio.')",
            "  $deadline = (Get-Date).AddSeconds(60)",
            "  while ((Get-Date) -lt $deadline) {",
            "    if (Get-Confirmed) { $confirmed = $true; break }",
            "    if ($newProcess.HasExited) { break }",
            "    Start-Sleep -Milliseconds 500",
            "  }",
            "  if (!$confirmed) { throw 'La nuova build non ha superato la conferma di avvio entro 60 secondi.' }",
            "} catch {",
            "  $failure = ($_ | Out-String).Trim()",
            "  Write-Log ('Aggiornamento non confermato: ' + $failure)",
            "  try { Stop-UpdateProcesses } catch { Write-Log ('Stop after failed update: ' + ($_ | Out-String)) }",
            "  $rollbackOk = $false",
            "  try {",
            "    if (Test-Path -LiteralPath $destination) {",
            "      if (Test-Path -LiteralPath $failed) { Remove-Item -LiteralPath $failed -Recurse -Force -ErrorAction SilentlyContinue }",
            "      $movedOut = $false",
            "      for ($attempt = 1; $attempt -le 20; $attempt++) {",
            "        try { [System.IO.Directory]::Move($destination, $failed); $movedOut = $true; break }",
            "        catch { Start-Sleep -Milliseconds 250 }",
            "      }",
            "      if (!$movedOut) { throw 'La nuova cartella è ancora in uso durante il rollback.' }",
            "    }",
            "    if (!(Test-Path -LiteralPath $destination) -and (Test-Path -LiteralPath $previous)) {",
            "      [System.IO.Directory]::Move($previous, $destination)",
            "    }",
            "    if (!(Test-Path -LiteralPath (Join-Path $destination 'Nebula.exe'))) { throw 'Dopo il rollback manca Nebula.exe.' }",
            "    $rollbackOk = $true",
            "  } catch {",
            "    Write-Log ('Rollback fallito: ' + ($_ | Out-String))",
            "    Write-Failure ($failure + [Environment]::NewLine + 'Rollback fallito: ' + ($_ | Out-String))",
            "  }",
            "  if ($rollbackOk) {",
            "    Remove-Item -LiteralPath $failed -Recurse -Force -ErrorAction SilentlyContinue",
            "    Remove-Item -LiteralPath $updated -Recurse -Force -ErrorAction SilentlyContinue",
            "    Remove-Item -LiteralPath $source -Recurse -Force -ErrorAction SilentlyContinue",
            "    Remove-Item -LiteralPath $zip -Force -ErrorAction SilentlyContinue",
            "    Remove-Item -LiteralPath $state -Force -ErrorAction SilentlyContinue",
            "    Remove-Item -LiteralPath $confirmation -Force -ErrorAction SilentlyContinue",
            "    Clear-RunOnce",
            "    Write-FailedPackage",
            "    Write-Failure $failure",
            "    $launch = Join-Path $destination 'Nebula.exe'",
            "    if (Test-Path -LiteralPath $launch) {",
            "      Start-Process -FilePath $launch -ArgumentList '--startup' | Out-Null",
            "      Write-Log 'Rollback completato; avviata la versione precedente.'",
            "    } else {",
            "      Write-Log 'Rollback completato ma nessun eseguibile avviabile.'",
            "    }",
            "  }",
            "  exit",
            "}",
            "",
            "try {",
            "  Remove-Item -LiteralPath $previous -Recurse -Force -ErrorAction SilentlyContinue",
            "  Remove-Item -LiteralPath $updated -Recurse -Force -ErrorAction SilentlyContinue",
            "  Remove-Item -LiteralPath $failed -Recurse -Force -ErrorAction SilentlyContinue",
            "  Remove-Item -LiteralPath $source -Recurse -Force -ErrorAction SilentlyContinue",
            "  Remove-Item -LiteralPath $zip -Force -ErrorAction SilentlyContinue",
            "  Remove-Item -LiteralPath $state -Force -ErrorAction SilentlyContinue",
            "  Remove-Item -LiteralPath $confirmation -Force -ErrorAction SilentlyContinue",
            "  Remove-Item -LiteralPath $failedVersionFile -Force -ErrorAction SilentlyContinue",
            "  Clear-RunOnce",
            "  Write-Log 'Aggiornamento confermato dalla nuova build.'",
            "} catch { Write-Log ('Final update cleanup failed: ' + ($_ | Out-String)) }"
        });
    }

    public static string Recover(string appDirectory, string token, string targetVersion, string targetSha)
    {
        string root = UpdateService.UpdatesDirectory;
        string updated = appDirectory + ".new";
        string previous = appDirectory + ".old";
        string failed = appDirectory + ".failed";
        string state = Path.Combine(root, "update-state.json");
        string confirmation = Path.Combine(root, "update-confirmed.txt");
        string failure = Path.Combine(root, "update-failed.txt");
        string failedVersion = Path.Combine(root, "failed-update.json");
        string log = Path.Combine(root, "apply-update.log");
        string runOnceKey = @"HKCU:\Software\Microsoft\Windows\CurrentVersion\RunOnce";

        return string.Join(Environment.NewLine, new List<string>
        {
            "param([switch]$Recover)",
            "$ErrorActionPreference = 'Stop'",
            "Set-Location -LiteralPath $env:SystemRoot",
            "$log = " + Q(log),
            "$failureReport = " + Q(failure),
            "$destination = " + Q(appDirectory),
            "$updated = " + Q(updated),
            "$previous = " + Q(previous),
            "$failed = " + Q(failed),
            "$state = " + Q(state),
            "$confirmation = " + Q(confirmation),
            "$failedVersionFile = " + Q(failedVersion),
            "$targetVersion = " + Q(targetVersion),
            "$targetSha = " + Q(targetSha),
            "$token = " + Q(token),
            "$runOnceKey = " + Q(runOnceKey),
            "$runOnceName = " + Q(RunOnceName),
            "",
            "function Write-Log([string]$message) {",
            "  $line = '[{0}] {1}' -f (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $message",
            "  Add-Content -LiteralPath $log -Value $line -Encoding utf8",
            "}",
            "function Get-Confirmed {",
            "  if (!(Test-Path -LiteralPath $confirmation)) { return $false }",
            "  try { $line = Get-Content -LiteralPath $confirmation -TotalCount 1 -ErrorAction Stop; return $line.Trim() -eq $token } catch { return $false }",
            "}",
            "function Clear-RunOnce {",
            "  Remove-ItemProperty -Path $runOnceKey -Name $runOnceName -ErrorAction SilentlyContinue",
            "}",
            "function Stop-UpdateProcesses {",
            "  Get-Process -Name 'Nebula' -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue",
            "  Start-Sleep -Milliseconds 1500",
            "  Get-Process -Name 'Nebula.Watchdog' -ErrorAction SilentlyContinue | Stop-Process -Force -ErrorAction SilentlyContinue",
            "  Start-Sleep -Milliseconds 250",
            "}",
            "function Remove-TransactionFiles {",
            "  Remove-Item -LiteralPath $failed -Recurse -Force -ErrorAction SilentlyContinue",
            "  Remove-Item -LiteralPath $updated -Recurse -Force -ErrorAction SilentlyContinue",
            "  Remove-Item -LiteralPath $state -Force -ErrorAction SilentlyContinue",
            "  Remove-Item -LiteralPath $confirmation -Force -ErrorAction SilentlyContinue",
            "  Clear-RunOnce",
            "}",
            "function Write-Failure([string]$message) {",
            "  $report = @('Aggiornamento non riuscito il ' + (Get-Date -Format 'yyyy-MM-dd HH:mm:ss'), $message) -join [Environment]::NewLine",
            "  Set-Content -LiteralPath $failureReport -Value $report -Encoding utf8",
            "}",
            "function Write-FailedPackage {",
            "  [ordered]@{ Version = $targetVersion; Sha256 = $targetSha; FailedUtc = (Get-Date).ToUniversalTime().ToString('O') } | ConvertTo-Json | Set-Content -LiteralPath $failedVersionFile -Encoding utf8",
            "}",
            "",
            "if (!(Test-Path -LiteralPath $state)) { Clear-RunOnce; exit 0 }",
            "Write-Log 'Recovery: found pending update state.'",
            "if (Get-Confirmed) {",
            "  Remove-Item -LiteralPath $previous -Recurse -Force -ErrorAction SilentlyContinue",
            "  Remove-Item -LiteralPath $failedVersionFile -Force -ErrorAction SilentlyContinue",
            "  Remove-TransactionFiles",
            "  Write-Log 'Recovery: confirmed update finalized.'",
            "  exit 0",
            "}",
            "$deadline = (Get-Date).AddSeconds(20)",
            "while ((Get-Date) -lt $deadline) {",
            "  if (Get-Confirmed) {",
            "    Remove-Item -LiteralPath $previous -Recurse -Force -ErrorAction SilentlyContinue",
            "    Remove-Item -LiteralPath $failedVersionFile -Force -ErrorAction SilentlyContinue",
            "    Remove-TransactionFiles",
            "    Write-Log 'Recovery: late confirmation accepted.'",
            "    exit 0",
            "  }",
            "  if (-not (Get-Process -Name 'Nebula' -ErrorAction SilentlyContinue)) { break }",
            "  Start-Sleep -Milliseconds 500",
            "}",
            "",
            "Stop-UpdateProcesses",
            "# A state can exist before the swap: if .old is absent, the live installation is intact.",
            "$preSwap = (Test-Path -LiteralPath $destination) -and -not (Test-Path -LiteralPath $previous)",
            "if ($preSwap) {",
            "  $launch = Join-Path $destination 'Nebula.exe'",
            "  if (!(Test-Path -LiteralPath $launch)) { Write-Failure 'Recovery: manca Nebula.exe prima dello swap.'; exit 1 }",
            "  Remove-TransactionFiles",
            "  Write-Failure 'Aggiornamento interrotto prima dello swap; installazione precedente intatta.'",
            "  Start-Process -FilePath $launch -ArgumentList '--startup' | Out-Null",
            "  Write-Log 'Recovery: pre-swap state cleared; previous installation preserved.'",
            "  exit 0",
            "}",
            "$rollbackOk = $false",
            "try {",
            "  if (Test-Path -LiteralPath $destination) {",
            "    if (Test-Path -LiteralPath $failed) { Remove-Item -LiteralPath $failed -Recurse -Force -ErrorAction SilentlyContinue }",
            "    $movedOut = $false",
            "    for ($attempt = 1; $attempt -le 20; $attempt++) {",
            "      try { [System.IO.Directory]::Move($destination, $failed); $movedOut = $true; break }",
            "      catch { Start-Sleep -Milliseconds 250 }",
            "    }",
            "    if (!$movedOut) { throw 'La cartella di Nebula è ancora in uso durante il recovery.' }",
            "  }",
            "  if (!(Test-Path -LiteralPath $destination) -and (Test-Path -LiteralPath $previous)) {",
            "    [System.IO.Directory]::Move($previous, $destination)",
            "  }",
            "  if (!(Test-Path -LiteralPath (Join-Path $destination 'Nebula.exe'))) { throw 'Dopo il recovery manca Nebula.exe.' }",
            "  $rollbackOk = $true",
            "} catch {",
            "  Write-Log ('Recovery rollback failed: ' + ($_ | Out-String))",
            "  Write-Failure ('Recovery rollback failed: ' + ($_ | Out-String))",
            "}",
            "if ($rollbackOk) {",
            "  Remove-TransactionFiles",
            "  Write-FailedPackage",
            "  Write-Failure 'Aggiornamento interrotto prima della conferma di avvio; ripristinata la versione precedente.'",
            "  $launch = Join-Path $destination 'Nebula.exe'",
            "  if (Test-Path -LiteralPath $launch) { Start-Process -FilePath $launch -ArgumentList '--startup' | Out-Null }",
            "  Write-Log 'Recovery: previous version restored.'",
            "}",
            "exit 0"
        });
    }
}
